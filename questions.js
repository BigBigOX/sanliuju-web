const ROUND_NAMES = { 1: '破冰轮', 2: '结对轮', 3: '默契轮' }

function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

function getPool(round) {
  if (round === 1) return [...POOL.L1]
  if (round === 2) return [...POOL.L2, ...POOL.L3]
  return [...POOL.L4]
}

function draw(round, count) {
  return shuffle(getPool(round)).slice(0, count)
}

